const RTL_UI_LANGUAGES = ["ar"];

const DEFAULT_UI_LANGUAGE = "es";

/**
 * UI strings for a language, with English filling any gap.
 * @param {string} lang - BCP47 primary subtag (e.g. 'es', 'pt-BR' → 'pt')
 */
function getUiStrings(lang) {
  const code = (lang || DEFAULT_UI_LANGUAGE).toLowerCase().split("-")[0];
  return { ...UI_STRINGS.en, ...(UI_STRINGS[code] || {}) };
}

